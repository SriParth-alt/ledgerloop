"""The compact §9.2 table that lives in README.md, and the splice that puts it there.

Rule 7 says every number in the README comes from `make eval`. For twelve days that was
enforced by intention alone, and intention lost: the Results table sat full of placeholder
dashes while `results/metrics.md` filled up with real figures beside it.

So the table is generated here, written to `results/summary.md`, and spliced into README
between markers. `tests/test_readme_results.py` asserts the two are byte-identical, which
turns rule 7 into something the build checks — the same move `tests/test_no_truth_leak.py`
makes for rule 6, and for the same reason: a hand-typed metric is indistinguishable from a
generated one by eye.

The README keeps its own copy rather than linking to `results/metrics.md`, because a judge
skimming the repository should meet the centrepiece of the pitch on the page rather than
one click away. `metrics.md` keeps the full per-fixture detail; this is the summary.
"""

from __future__ import annotations

from pathlib import Path

from eval.ablation import NOT_MEASURED, AblationArm

RESULTS_START = "<!-- RESULTS:START -->"
RESULTS_END = "<!-- RESULTS:END -->"

#: The order §9.2 fixes. Rendered from this rather than from dictionary order so two
#: published tables cannot disagree about which configuration came first.
ARM_ORDER = ("T0 only", "T0 + T1", "T0 + T1 + T2", "Full cascade", "LLM-only baseline")

FIXTURE_ORDER = ("easy", "realistic", "adversarial")


def _cell(value: str) -> str:
    return value


def render_summary(arms: dict[str, list[AblationArm]]) -> str:
    """Render the compact ablation table.

    One row per fixture and configuration. The fixture column is repeated rather than
    grouped-and-blanked because a row lifted out of context — quoted in a slide, pasted
    into a chat — must still say which fixture it describes. The same cascade scores 100%
    on `easy` and 67.9% on `adversarial`; a match rate without its fixture is not a
    reproducible claim.
    """
    lines = [
        "| Fixture | Configuration | Auto-match | Precision | False-match | Adjudications |",
        "|---|---|---|---|---|---|",
    ]

    ordered = [name for name in FIXTURE_ORDER if name in arms]
    ordered += [name for name in arms if name not in FIXTURE_ORDER]

    for fixture in ordered:
        by_label = {arm.label: arm for arm in arms[fixture]}
        for label in ARM_ORDER:
            arm = by_label.get(label)
            if arm is None:
                continue
            if arm.metrics is None:
                # A blank cell reads as an oversight and a zero reads as a measurement
                # that found nothing. Only "not measured" is true (ADR-032).
                lines.append(
                    f"| `{fixture}` | {label} | *{NOT_MEASURED}* | — | — | — |"
                )
                continue
            m = arm.metrics
            adjudications = str(m.adjudications) if 3 in arm.tiers else "0"
            lines.append(
                f"| `{fixture}` | {label} | {m.auto_match_rate:.1%} | {m.precision:.1%} "
                f"| **{m.false_match_rate:.1%}** | {adjudications} |"
            )

    lines += [
        "",
        "Throughput is reported separately in",
        "[`results/throughput.md`](results/throughput.md), because a timing is an",
        "observation about a machine rather than a property of the code and cannot be",
        "byte-identical across two of them. *Adjudications* is how many credits the",
        "configuration put to the model — the",
        "figure §9.2 compares, and a property of the architecture rather than of the",
        "response cache (ADR-033). Generated by `make eval`; see",
        "[`results/metrics.md`](results/metrics.md) for per-fixture detail including the",
        "exception breakdown by reason code.",
    ]
    return "\n".join(lines)


def splice(readme: Path, block: str) -> None:
    """Replace the marked region of README.md with ``block``.

    Idempotent: `make eval` runs repeatedly, and a splice that accumulated copies or ate a
    marker on the second pass would corrupt the README on the day it is read most.

    Raises rather than repairing a README with no markers. Appending the table, or
    silently doing nothing, both end with a README whose numbers are stale and whose
    staleness is invisible — which is the failure this whole module exists to prevent.
    """
    readme = Path(readme)
    text = readme.read_text(encoding="utf-8")

    if RESULTS_START not in text or RESULTS_END not in text:
        raise ValueError(
            f"{readme} has no {RESULTS_START} / {RESULTS_END} marker pair — refusing to "
            f"guess where the generated results table belongs"
        )

    start = text.index(RESULTS_START) + len(RESULTS_START)
    end = text.index(RESULTS_END)
    readme.write_text(
        text[:start] + "\n" + block.strip() + "\n" + text[end:],
        encoding="utf-8",
        newline="\n",
    )


def render_throughput(arms: dict[str, list[AblationArm]]) -> str:
    """Render the timing table, and say plainly that it is not reproducible.

    Track 04's bar names throughput alongside accuracy and the exception list, so it has to
    be published. But a timing is an observation about a machine under a particular load,
    not a property of the code: the same commit measured 1,340 credits/s on a laptop and
    952/s on a CI runner.

    Every other published figure is byte-identical on re-run, and CI fails the build if one
    drifts (ADR-036). Putting a timing inside that guarantee would mean either a permanently
    red build or a weakened guarantee, and the guarantee is what makes the other numbers
    worth trusting. So this file lives outside the check and states its own limits.
    """
    import platform

    lines = [
        "# Throughput",
        "",
        "> Generated by `ledgerloop evaluate`. **Not byte-reproducible, and deliberately",
        "> outside the drift check** that guards every other published figure: a timing",
        "> describes a machine, not the code. The same commit measures differently on a",
        "> laptop and a CI runner, so treat these as an order of magnitude.",
        "",
        f"Measured on: `{platform.system()} {platform.machine()}`, "
        f"Python {platform.python_version()}.",
        "",
        "Timed around reconciliation only. Including generation and ingest would measure",
        "the fixture rather than the cascade.",
        "",
        "**The two model arms are replayed from the committed response cache, so their",
        "throughput excludes API latency.** As a comparison of matcher work that is fair; as",
        "wall-clock it flatters both arms, and it flatters the LLM-only baseline most because",
        "that arm makes the most calls. At the free tier's pacing its 165 live calls take",
        "minutes, not the second or two shown here.",
        "",
        "| Fixture | Configuration | Credits/s | Seconds | Credits |",
        "|---|---|---|---|---|",
    ]

    ordered = [name for name in FIXTURE_ORDER if name in arms]
    ordered += [name for name in arms if name not in FIXTURE_ORDER]

    for fixture in ordered:
        by_label = {arm.label: arm for arm in arms[fixture]}
        for label in ARM_ORDER:
            arm = by_label.get(label)
            if arm is None or arm.metrics is None:
                continue
            m = arm.metrics
            lines.append(
                f"| `{fixture}` | {label} | {m.throughput:,.0f} | {m.seconds:.2f} "
                f"| {m.credits_total} |"
            )
    return "\n".join(lines)

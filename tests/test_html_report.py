# --- self-containment ---------------------------------------------------------------


def test_the_page_makes_no_outward_request() -> None:
    """The failure this test exists to prevent is invisible until the demo.

    A CDN font or script resolves fine on the machine that built it and fails on a plane,
    on a locked-down network, or in a judging room with bad wifi.

    Checks for constructs that *fetch* — not for the characters "https://". A URL can
    legitimately appear as text: Pydantic's validation errors carry one, and that message
    is displayed verbatim as the schema gate's reason. Asserting the substring would
    pressure someone into stripping a real diagnostic to satisfy a test that was measuring
    the wrong thing.
    """
    html = render_report(_data())

    assert not re.search(r"<link[^>]", html)
    assert not re.search(r"<script[^>]*\ssrc\s*=", html)
    assert not re.search(r"<img[^>]*\ssrc\s*=", html)
    assert "@import" not in html
    assert not re.search(r"url\(\s*['\"]?https?:", html)


def test_a_url_inside_displayed_text_does_not_count_as_a_request() -> None:
    """Encodes the distinction the test above rests on, so nobody re-tightens it.

    Pydantic appends a documentation link to its validation errors, and that text is shown
    as the reason the schema gate rejected a response. It is content. The page fetches
    nothing.
    """
    html = render_report(_data(adjudications=[Adjudication(
        bank_txn_id="BNK1", credit_paise=100, value_date="2026-08-01", narration="n",
        candidates=[], candidates_total=1, prompt="p", raw_response="r",
        stages=[GateStage(gate="schema", passed=False,
                          detail="see https://errors.pydantic.dev/2.13/v/string_too_long")],
        verdict="LLM_INVALID_OUTPUT", scripted=False)]))

    assert "errors.pydantic.dev" in html
    assert not re.search(r"<link[^>]", html)
    assert not re.search(r"<script[^>]*\ssrc\s*=", html)


def test_the_page_is_one_file_with_no_placeholder_left_behind() -> None:
    html = render_report(_data())

    # Not a naive brace check: CSS media queries legitimately end in "}}". Look for the
    # substitution sentinels this module actually uses.
    assert "__BLURB__" not in html and "__GW__" not in html
    assert html.lstrip().startswith("<!doctype html>")
    assert html.rstrip().endswith("</html>")


# --- nothing is computed in the template --------------------------------------------


def test_every_headline_figure_comes_from_the_passed_metrics() -> None:
    """Rule 7, applied to the renderer. If the template derived a rate it could disagree
    with `results/metrics.md`, and two sources for one number is how a wrong number
    ships."""
    html = render_report(_data(metrics=_metrics(
        auto_match_rate=0.123, precision=0.456, false_match_rate=0.789)))

    assert "12.3%" in html
    assert "45.6%" in html
    assert "78.9%" in html


def test_a_run_with_no_metrics_still_renders() -> None:
    """`reconcile` can run without truth available. The page must degrade to the parts it
    can show rather than failing to generate at all."""
    html = render_report(_data(metrics=None))

    assert "demo" in html
    assert "not scored" in html.lower()



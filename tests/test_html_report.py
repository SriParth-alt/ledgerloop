"""The HTML report — §12's buffer-policy deliverable, and the demo surface.

§12 cut the FastAPI + React UI and named the fallback: *a static HTML report generated by
the CLI*. This is that report. One self-contained file, no server, no build step, no
network — a judge opens it on a laptop with no key and no internet.

Two properties carry the weight here, and both are easy to lose silently:

**Self-containment.** A CDN reference that resolves on a developer's machine and fails on
a plane is the worst kind of bug: invisible until the moment it is being demonstrated. So
the page must contain no outward reference of any kind — no script src, no stylesheet
link, no remote font, no image URL.

**Nothing is computed in the template.** Every figure is passed in, already scored. A
renderer that derives a percentage is a renderer that can disagree with
`results/metrics.md`, and rule 7 exists precisely because two sources for one number is
how a wrong number ships.

The renderer is also deliberately *pure* — data in, string out, no database, no filesystem,
no ground truth. That is what lets it live in `ledgerloop/` at all: `eval/` computes
precision, because `eval/` is the only package permitted to read truth, and hands the
result over. `tests/test_no_truth_leak.py` stays untouched.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from eval.metrics import RunMetrics
from ledgerloop.exceptions.codes import ExceptionCode

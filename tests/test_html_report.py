# --- the replay itself --------------------------------------------------------------


def test_replay_reads_the_committed_cache_and_calls_nothing(tmp_path: Path) -> None:
    """Replays are built from cached responses, so the demo cannot rate-limit, time out,
    or answer differently on stage. Both of those failures happened during the real
    sweeps (ADR-031)."""
    from ledgerloop.report.replay import replay_tier3

    cases = replay_tier3(
        fixture="adversarial", records=250, seed=42,
        cache_dir=COMMITTED_CACHE, workdir=tmp_path, limit=4,
    )

    assert cases, "no cached adjudications found — has the cache moved?"
    for case in cases:
        assert case.prompt and case.raw_response
        assert case.stages


def test_replay_finds_a_rejection_not_only_successes(tmp_path: Path) -> None:
    """A demo showing only clean matches proves nothing about the gates. The rejections
    are the evidence."""
    from ledgerloop.report.replay import replay_tier3

    cases = replay_tier3(
        fixture="adversarial", records=250, seed=42,
        cache_dir=COMMITTED_CACHE, workdir=tmp_path, limit=6,
    )
    verdicts = {c.verdict for c in cases}

    assert len(verdicts) > 1, f"every replayed case ended the same way: {verdicts}"
    assert any(not s.passed for c in cases for s in c.stages)


def test_replay_is_deterministic(tmp_path: Path) -> None:
    """§7.4. Two replays of one fixture must produce the same cases in the same order, or
    the demo is not reproducible and neither is the page."""
    from ledgerloop.report.replay import replay_tier3

    kw = dict(fixture="adversarial", records=250, seed=42, cache_dir=COMMITTED_CACHE, limit=3)
    first = replay_tier3(workdir=tmp_path / "a", **kw)  # type: ignore[arg-type]
    second = replay_tier3(workdir=tmp_path / "b", **kw)  # type: ignore[arg-type]

    assert [c.bank_txn_id for c in first] == [c.bank_txn_id for c in second]
    assert [c.verdict for c in first] == [c.verdict for c in second]


def test_replay_never_reaches_ground_truth() -> None:
    """`ledgerloop/` may not read truth_links.csv. The replay lives there, so it must be
    buildable from the run and the cache alone.

    Checks for the tokens a leak would actually introduce rather than the word "truth" —
    the module's own docstring says it does not read ground truth, and a test that cannot
    tell an explanation from a violation is a test that will be silenced rather than
    fixed. `tests/test_no_truth_leak.py` remains the authoritative guard for the package
    as a whole; this is a local assertion about the newest module in it.
    """
    source = (REPO_ROOT / "ledgerloop" / "report" / "replay.py").read_text(encoding="utf-8")

    assert "truth_links" not in source
    assert "from eval" not in source
    assert "import eval" not in source

def test_values_from_the_bank_file_are_escaped() -> None:
    """Narration is free text arriving from a third party. It lands in the DOM, so it is
    escaped — not because a bank statement is hostile, but because a renderer that trusts
    its input is one CSV away from a broken page."""
    nasty = '<script>alert("x")</script>'
    html = render_report(_data(provenance=[ProvenanceRow(
        bank_txn_id=nasty, settlement_ids=("STL1",), tier=0, rule_id="T0",
        confidence=1.0, evidence=[], fingerprints=("abc",),
        model_name=None, prompt_version=None)]))

    assert "<script>alert" not in html
    assert "&lt;script&gt;" in html


